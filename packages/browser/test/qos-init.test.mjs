check("restart stops dependents rather than leaving stale instances",service("dependent").phase==="blocked");
val(await run("svc start init dependent","svc_start"));
check("dependent can start after base is ready",service("dependent").phase==="running");
for(let i=0;i<6;i++)val(await run("svc health init bad","svc_health"));
