import assert from 'node:assert/strict';
import {generateKeyPairSync,sign} from 'node:crypto';
import {mkdtemp,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openJournal} from './authority-journal.mjs';
import {createIdentityContext,initializeIdentityJournal,applySigned,auditSigned} from './authority-identity.mjs';
const pairs=Array.from({length:4},()=>generateKeyPairSync('ed25519'));
const entries=pairs.map(({publicKey},actor)=>({actor,publicKey}));
const context=createIdentityContext('synthetic-identity-fixture',entries);
const reverse=createIdentityContext(context.stream,[...entries].reverse());
assert.equal(reverse.registryDigest,context.registryDigest);
assert.throws(()=>createIdentityContext(context.stream,[...entries,{actor:8,publicKey:pairs[0].publicKey}]),/duplicate registry key/);
assert.throws(()=>createIdentityContext(context.stream,[...entries,entries[0]]),/invalid registry entry/);
assert.throws(()=>createIdentityContext(context.stream,entries.slice(1)),/missing root key/);
assert.throws(()=>createIdentityContext(context.stream,[{actor:0,publicKey:generateKeyPairSync('ec',{namedCurve:'prime256v1'}).publicKey}]),/invalid registry entry/);
const dir=await mkdtemp(join(tmpdir(),'authority-identity-'));
const db=join(dir,'identity.db');
const grant=(request,id,target,parent=0,mask=10)=>({kind:'grant',request,id,target,parent,mask,process:7});
const exec=(request,parent,right=1)=>({kind:'execute',request,parent,right,process:7});
const revoke=(request,id)=>({kind:'revoke',request,id});
const signed=(actor,c,keyActor=actor,ctx=context)=>ctx.signEnvelope(actor,c,pairs[keyActor].privateKey);
const checks=['canonical registry ordering; duplicate actors/keys, missing root and non-Ed25519 keys rejected'];
try{
 initializeIdentityJournal(db,context);
 const yes=(a,c)=>{const envelope=signed(a,c),r=applySigned(db,context,envelope);assert(r.accepted);return envelope;};
 const no=(envelope,reason='invalid-authentication')=>{
   const before=auditSigned(db,context);
   assert.deepEqual(applySigned(db,context,envelope),{accepted:false,reason});
   assert.deepEqual(auditSigned(db,context),before);
 };
 const g=grant(1,1,1);
 no(signed(0,g,2)); // another registered key does not authenticate the root
 const tamper=structuredClone(signed(0,g));tamper.body.command.target=2;no(tamper);
 const relabel=structuredClone(signed(0,g));relabel.body.actor=2;no(relabel);
 const malformed=structuredClone(signed(0,g));malformed.signature+='\n';no(malformed);
 const canon=x=>JSON.stringify(x,(_k,v)=>v&&typeof v==='object'&&!Array.isArray(v)?Object.fromEntries(Object.keys(v).sort().map(k=>[k,v[k]])):v);
 const unknown=structuredClone(signed(0,g));unknown.body.actor=99;
 unknown.signature=sign(null,Buffer.from(canon(unknown.body)),pairs[0].privateKey).toString('hex');no(unknown);
 const extra=structuredClone(signed(0,g));extra.body.command.extra=true;
 extra.signature=sign(null,Buffer.from(canon(extra.body)),pairs[0].privateKey).toString('hex');no(extra);
 no(null);
 assert.equal(auditSigned(db,context).receipts,0);
 checks.push('wrong actor key, signed unknown actor, tamper, actor relabel, signed extra field and malformed envelope refused without state changes');
 const otherStream=createIdentityContext('other-fixture',entries);
 no(signed(0,g,0,otherStream));
 const otherRegistry=createIdentityContext(context.stream,[...entries.slice(0,3),{actor:3,publicKey:generateKeyPairSync('ed25519').publicKey}]);
 no(signed(0,g,0,otherRegistry));
 assert.throws(()=>initializeIdentityJournal(db,otherRegistry),/identity context mismatch/);
 assert.throws(()=>auditSigned(db,otherStream),/identity context mismatch/);
 assert.throws(()=>applySigned(db,otherRegistry,signed(0,g,0,otherRegistry)),/identity context mismatch/);
 checks.push('cross-stream and cross-registry substitution refused; existing database cannot be rebound');
 const first=yes(0,g);no(first,'replay');
 no(signed(0,grant(1,2,2)),'request-conflict');
 no(signed(2,exec(2,1)),'wrong-holder');
 no(signed(1,exec(2,1,5)),'missing-right');
 no(signed(1,revoke(2,0)),'owner-only');
 const action=yes(1,exec(2,1));no(action,'replay');
 checks.push('valid signatures remain subject to holder, right, owner and replay checks; denied request ID not consumed');
 yes(1,grant(3,2,2,1,2));yes(0,grant(4,3,3,0,2));
 yes(0,revoke(5,1));no(signed(2,exec(6,2)),'revoked');
 yes(3,exec(6,3));
 initializeIdentityJournal(db,reverse);
 assert.equal(auditSigned(db,reverse).receipts,6);
 checks.push('signed ancestor revocation survives reopen; sibling executes; journal audit re-verifies all actor signatures');
 const raw=openJournal(db);
 const row=raw.prepare('SELECT envelope FROM identity_receipt WHERE ordinal=1').get();
 const changed=JSON.parse(row.envelope);changed.signature='00'.repeat(64);
 raw.prepare('UPDATE identity_receipt SET envelope=? WHERE ordinal=1').run(JSON.stringify(changed));raw.close();
 assert.throws(()=>auditSigned(db,context),/receipt authentication failed/);
 checks.push('tampered stored signature detected during full journal audit');
 const report={schema:'authority-identity-witness/1',source:process.env.AUTHORITY_HEAD,testedMerge:process.env.GITHUB_SHA,checks,registryDigest:context.registryDigest,scope:'isolated Ed25519 actor-bound durable journal; fixed trusted registry; no production identity replacement, key rotation, distributed consensus or quantum-security claim'};
 await writeFile('authority-identity.json',JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report,null,2));
}finally{await rm(dir,{recursive:true,force:true});}
